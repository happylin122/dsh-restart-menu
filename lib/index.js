/**
 * dsh-restart-menu — host half.
 *
 * The desktop shell draws the Windows caption menu (应用 / 编辑) from a fixed
 * template inside the Electron main process, so a plugin cannot append an item
 * to that native popup. This plugin instead:
 *
 *   1. exposes `POST /plugins/dsh-restart-menu/restart` on the DSH web server;
 *   2. the browser half renders a "重启" button beside 应用 / 编辑 and calls it;
 *   3. the host writes a tiny detached WSH helper (VBScript) that waits a
 *      moment, stops every `DeepSeek Harness.exe` image and starts the
 *      executable again through the shell.
 *
 * Why a detached helper instead of `app.relaunch()`: this code runs in the DSH
 * host process (Electron in Node mode), not in the Electron main process, so the
 * only way to restart the whole app is to orchestrate it from outside the
 * killing tree.
 *
 * Why VBScript and not a `.cmd`: a batch helper needs a console, and a console
 * child started with a hidden window passes that hidden show-state on to the
 * app it launches — the app then runs with no visible window. `wscript.exe //B`
 * is a GUI-subsystem host with no console at all, and it re-launches the app
 * through `explorer.exe`, the same ShellExecute path a desktop double-click
 * takes, so the new window is always visible.
 *
 * @module dsh-restart-menu
 */

import { spawn } from 'node:child_process'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import process from 'node:process'

/** Plugin name, used as the cordis entry id and the client bundle id. */
export const name = 'dsh-restart-menu'

/** Services this plugin needs; the web route is injected lazily. */
export const inject = []

const PLUGIN_ID = 'dsh-restart-menu'
const ROUTE_PATH = `/plugins/${PLUGIN_ID}/restart`
const LOG_FILE = path.join(os.tmpdir(), `${PLUGIN_ID}.log`)
const HELPER_FILE = path.join(os.tmpdir(), `${PLUGIN_ID}-helper.vbs`)
const LEGACY_HELPER_FILE = path.join(os.tmpdir(), `${PLUGIN_ID}-helper.cmd`)

/** Default delay before the helper stops the app, so the HTTP reply can flush. */
const DEFAULT_DELAY_MS = 1500

/** How long the helper waits for the old image to disappear. */
const MAX_SETTLE_MS = 20_000

/** True when this process is the desktop host (Electron runtime with Node mode). */
function isDesktopHost() {
  if (process.platform !== 'win32') return false
  if (process.env.ELECTRON_RUN_AS_NODE !== '1') return false
  return /\.exe$/i.test(process.execPath) && !/[\\/]node\.exe$/i.test(process.execPath)
}

/** Absolute executable path of the running desktop app. */
function appExecutable() {
  return isDesktopHost() ? process.execPath : undefined
}

/** Append one line to the helper log (never throws). */
function appendLog(line) {
  try {
    fs.appendFileSync(LOG_FILE, `[${new Date().toISOString()}] ${line}\r\n`)
  } catch {
    /* logging must never break the restart path */
  }
}

/** Quote a value as a VBScript string literal. */
function vbsString(value) {
  return `"${String(value).replace(/"/g, '""')}"`
}

/** Quote a value for a Windows batch file. */
function batchQuote(value) {
  return `"${String(value).replace(/"/g, '""')}"`
}

/**
 * The VBScript helper. ASCII only: WSH reads a `.vbs` file in the system
 * codepage, so non-ASCII text would be mangled.
 *
 * Arguments: `run|probe` and the wait before the kill, in milliseconds.
 */
function helperScript(exe, delayMs) {
  const image = path.basename(exe)
  const dir = path.dirname(exe)
  return [
    "' Generated by dsh-restart-menu. Rewritten on every restart request; safe to delete.",
    'Option Explicit',
    'Dim fso, sh, argv, mode, waitMs, logPath, exePath, exeDir, image',
    'Dim rc, i, finished',
    '',
    `logPath = ${vbsString(LOG_FILE)}`,
    `exePath = ${vbsString(exe)}`,
    `exeDir = ${vbsString(dir)}`,
    `image = ${vbsString(image)}`,
    '',
    'Set fso = CreateObject("Scripting.FileSystemObject")',
    'Set sh = CreateObject("WScript.Shell")',
    'Set argv = WScript.Arguments',
    '',
    'mode = "run"',
    'If argv.Count > 0 Then mode = LCase(argv(0))',
    `waitMs = ${Math.max(0, Math.round(delayMs))}`,
    'If argv.Count > 1 Then',
    '  If IsNumeric(argv(1)) Then waitMs = CLng(argv(1))',
    'End If',
    '',
    'Sub LogLine(text)',
    '  Dim stream',
    '  On Error Resume Next',
    '  Set stream = fso.OpenTextFile(logPath, 8, True)',
    '  stream.WriteLine "[" & Now & "] " & text',
    '  stream.Close',
    '  On Error GoTo 0',
    'End Sub',
    '',
    "' Runs a console command with a hidden window and returns its exit code.",
    'Function Silent(command)',
    '  Silent = sh.Run("cmd.exe /d /c " & command, 0, True)',
    'End Function',
    '',
    "' True while at least one process with the target image name is alive.",
    'Function ImageUp()',
    '  Dim probe',
    '  probe = "tasklist /FI " & Chr(34) & "IMAGENAME eq " & image & Chr(34)',
    '  probe = probe & " /NH | find /I " & Chr(34) & image & Chr(34) & " >nul"',
    '  ImageUp = (Silent(probe) = 0)',
    'End Function',
    '',
    'LogLine "helper start (mode=" & mode & ", wait=" & waitMs & "ms)"',
    '',
    'If Not fso.FileExists(exePath) Then',
    '  LogLine "ABORT executable not found: " & exePath',
    '  WScript.Quit 2',
    'End If',
    '',
    'If mode = "probe" Then',
    '  LogLine "probe: " & image & " up=" & ImageUp()',
    '  rc = Silent("tasklist /FI " & Chr(34) & "IMAGENAME eq " & image & Chr(34) & " /FO CSV /NH >> " & Chr(34) & logPath & Chr(34) & " 2>&1")',
    '  LogLine "probe: tasklist exit=" & rc',
    '  LogLine "probe: done"',
    '  WScript.Quit 0',
    'End If',
    '',
    'WScript.Sleep waitMs',
    'LogLine "stopping image " & image',
    'rc = Silent("taskkill /F /IM " & Chr(34) & image & Chr(34))',
    'LogLine "taskkill exit=" & rc',
    '',
    'finished = False',
    `For i = 1 To ${Math.ceil(MAX_SETTLE_MS / 250)}`,
    '  If Not ImageUp() Then',
    '    finished = True',
    '    Exit For',
    '  End If',
    '  WScript.Sleep 250',
    'Next',
    'If finished Then',
    '  LogLine "image stopped"',
    'Else',
    `  LogLine "WARN image still running after ${Math.round(MAX_SETTLE_MS / 1000)}s"`,
    'End If',
    '',
    "' Launch through the shell: the same path as a desktop double-click, so the",
    "' new window is visible even though this helper itself has no window.",
    'sh.CurrentDirectory = exeDir',
    'For i = 1 To 5',
    '  LogLine "launching (attempt " & i & ") " & exePath',
    '  rc = Silent("start " & Chr(34) & Chr(34) & " explorer.exe " & Chr(34) & exePath & Chr(34))',
    '  If rc <> 0 Then LogLine "WARN explorer exit=" & rc',
    '  WScript.Sleep 1500',
    '  If ImageUp() Then',
    '    LogLine "launched"',
    '    WScript.Quit 0',
    '  End If',
    'Next',
    'LogLine "WARN launch not detected after 5 attempts"',
    'WScript.Quit 1',
    ''
  ].join('\r\n')
}

/**
 * Batch fallback for machines where Windows Script Host is unavailable.
 * Kept intentionally small: it can only kill and relaunch, no probing.
 */
function fallbackScript(exe, delayMs) {
  const image = path.basename(exe)
  const dir = path.dirname(exe)
  return [
    '@echo off',
    'setlocal enableextensions',
    'set "ELECTRON_RUN_AS_NODE="',
    'set "DSH_DESKTOP_NODE_EXECUTABLE="',
    `set "LOG=${LOG_FILE}"`,
    `set "IMAGE=${image}"`,
    `set "EXE=${exe}"`,
    `set "DIR=${dir}"`,
    'echo [%DATE% %TIME%] fallback helper start >> "%LOG%"',
    `set /a "PINGS=${Math.max(0, Math.round(delayMs))}/1000+1"`,
    'ping -n %PINGS% 127.0.0.1 >nul',
    'taskkill /F /IM "%IMAGE%" >> "%LOG%" 2>&1',
    'ping -n 6 127.0.0.1 >nul',
    'explorer.exe "%EXE%"',
    'echo [%DATE% %TIME%] fallback helper done >> "%LOG%"',
    'endlocal',
    ''
  ].join('\r\n')
}

/**
 * Write (or rewrite) the relaunch helper scripts.
 * @param exe Absolute path of the desktop executable.
 * @param delayMs How long the helper waits before stopping the app.
 * @returns the VBS helper path.
 */
function writeHelper(exe, delayMs = DEFAULT_DELAY_MS) {
  fs.writeFileSync(HELPER_FILE, helperScript(exe, delayMs), 'utf8')
  fs.writeFileSync(LEGACY_HELPER_FILE, fallbackScript(exe, delayMs), 'utf8')
  return HELPER_FILE
}

/** Host executable + arguments that run the helper without a console window. */
function helperRuntime(mode, delayMs) {
  const systemRoot = process.env.SystemRoot ?? process.env.windir ?? 'C:\\Windows'
  const wscript = path.join(systemRoot, 'System32', 'wscript.exe')
  if (fs.existsSync(wscript)) {
    return { file: wscript, args: ['//B', '//Nologo', HELPER_FILE, mode, String(delayMs)] }
  }
  return { file: 'cmd.exe', args: ['/d', '/c', LEGACY_HELPER_FILE] }
}

/** Spawn the helper fully detached so it survives the restart it performs. */
function spawnHelper(args, delayMs = DEFAULT_DELAY_MS) {
  const env = { ...process.env }
  delete env.ELECTRON_RUN_AS_NODE
  delete env.DSH_DESKTOP_NODE_EXECUTABLE
  const runtime = helperRuntime(args[0] ?? 'run', delayMs)
  const child = spawn(runtime.file, runtime.args, {
    cwd: os.tmpdir(),
    env,
    detached: true,
    stdio: 'ignore',
    windowsHide: true
  })
  child.unref()
  return child.pid
}

/** Serialize responses as JSON. */
function sendJson(res, status, payload) {
  const body = JSON.stringify(payload)
  res.writeHead(status, {
    'content-type': 'application/json; charset=utf-8',
    'cache-control': 'no-store',
    'content-length': Buffer.byteLength(body)
  })
  res.end(body)
}

/** Only loopback callers may restart the machine-local app. */
function isLoopback(req) {
  const address = req.socket?.remoteAddress
  return address === '127.0.0.1' || address === '::1' || address === '::ffff:127.0.0.1'
}

let restarting = false

/** Build the request handler. */
function createHandler() {
  return (req, res) => {
    const url = new URL(req.url ?? '/', 'http://127.0.0.1')
    const probe = url.searchParams.get('probe') === '1'

    if (req.method === 'GET') {
      sendJson(res, 200, {
        plugin: PLUGIN_ID,
        desktop: isDesktopHost(),
        platform: process.platform,
        pid: process.pid,
        ppid: process.ppid,
        executable: process.execPath,
        log: LOG_FILE,
        helper: HELPER_FILE
      })
      return
    }

    if (req.method !== 'POST') {
      res.writeHead(405, { allow: 'GET, POST' })
      res.end()
      return
    }

    if (!isLoopback(req)) {
      sendJson(res, 403, { error: 'restart is only available from this machine' })
      return
    }
    if (req.headers['x-dsh-restart-menu'] !== '1') {
      sendJson(res, 403, { error: 'missing x-dsh-restart-menu confirmation header' })
      return
    }

    const exe = appExecutable()
    if (exe === undefined) {
      sendJson(res, 409, {
        error: 'dsh-restart-menu only restarts the DeepSeek Harness desktop app',
        platform: process.platform,
        executable: process.execPath
      })
      return
    }

    const requestedDelay = Number(url.searchParams.get('delay') ?? DEFAULT_DELAY_MS)
    const delay = Number.isFinite(requestedDelay)
      ? Math.min(Math.max(requestedDelay, 200), 60_000)
      : DEFAULT_DELAY_MS

    try {
      writeHelper(exe, delay)
    } catch (error) {
      sendJson(res, 500, { error: `cannot write helper: ${String(error?.message ?? error)}` })
      return
    }

    if (probe) {
      // Non-destructive self test: the helper logs its view of the world, no kill.
      const pid = spawnHelper(['probe'], 0)
      appendLog(`probe requested (helper pid ${String(pid)}, executable ${exe})`)
      sendJson(res, 200, { ok: true, probe: true, helperPid: pid, log: LOG_FILE })
      return
    }

    if (restarting) {
      sendJson(res, 409, { error: 'a restart is already in progress' })
      return
    }
    restarting = true

    let helperPid
    try {
      const pid = spawnHelper(['run'], delay)
      helperPid = pid
      appendLog(`restart accepted (app ${exe}, helper pid ${String(pid)}, delay ${delay}ms)`)
    } catch (error) {
      restarting = false
      sendJson(res, 500, { error: `cannot spawn helper: ${String(error?.message ?? error)}` })
      return
    }

    sendJson(res, 202, {
      ok: true,
      restarting: true,
      executable: exe,
      delayMs: delay,
      helperPid,
      log: LOG_FILE
    })
  }
}

/**
 * Register the restart route with the DSH web server.
 * @param ctx plugin context.
 */
export function apply(ctx) {
  if (process.platform !== 'win32') {
    ctx.logger?.info?.('dsh-restart-menu: only the Windows desktop app is supported')
    return
  }

  ctx.inject(['webServer'], (webCtx) => {
    const webServer = webCtx.webServer
    webCtx.effect(
      () =>
        webServer.register({
          kind: 'exact',
          path: ROUTE_PATH,
          handler: createHandler()
        }),
      'dsh-restart-menu: restart route'
    )
  })

  // Refresh the packaged helper scripts at boot so stale ones never survive.
  if (isDesktopHost()) {
    try {
      writeHelper(process.execPath)
    } catch {
      /* written again when the button is pressed */
    }
  }
}

